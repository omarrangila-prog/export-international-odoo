#!/usr/bin/env python3
"""Screen inventory: every screenshot of the gallery with its route, role, the audit findings that apply (EXI-nn) and their status.
    python3 tests/gen_screen_inventory.py [db]      (needs the staging database for the menu -> action map)
The findings come from the client's screenshot review of 26 Oct 2026; STATUS below is edited as each one is fixed AND tested."""
import json
import os
import re
import subprocess
import sys

ROOT = os.path.join(os.path.dirname(__file__), '..')
DB = sys.argv[1] if len(sys.argv) > 1 else 'ei20b'
G = os.path.join(ROOT, 'docs', 'ui', 'gallery')

FINDINGS = {
    'EXI-01': "A visible New that ends in an Access Error",
    'EXI-02': "Very tall phone page; the first job is buried",
    'EXI-03': "Phone record: stacked read-only fields, scrolling line table, late activity",
    'EXI-04': "Tables: truncated headings, weak numeric hierarchy, no density control",
    'EXI-05': "Reports: generic charts, no shared KPI strip / filters across chart, pivot and list",
    'EXI-06': "Executive Home: tall, repeated facts, next decisions not first",
    'EXI-07': "Party 360: disconnected cards, repeated links, very long page",
    'EXI-08': "Bank matching: nested scrolling, little orientation once scrolled",
    'EXI-09': "Records: width wasted on an empty activity panel; long one-line fields; clipped grids",
    'EXI-10': "Report catalog: status labels need Preview / Verified / Pending external data",
    'EXI-11': "Connections must never imply a live integration",
    'EXI-12': "Ask must stay a source-backed, rule-based record assistant (preserve)",
    'EXI-13': "Dark mode contrast on muted text, chips, tables, error panels",
    'EXI-14': "Login page disconnected from the ERP shell",
    'EXI-15': "Empty states: unused white area, inconsistent next action",
    'EXI-16': "Provenance of figures (posted / provisional / suggested / bank-confirmed) must be consistent",
}
# edited as findings are fixed and tested; anything not listed is "open"
STATUS = json.load(open(os.path.join(os.path.dirname(__file__), 'inventory_status.json'))) if os.path.exists(os.path.join(os.path.dirname(__file__), 'inventory_status.json')) else {}

def menu_routes():
    sql = """with recursive m as (select id, parent_id, coalesce(name->>'en_US', name::text) as nm, action from ir_ui_menu where parent_id is null
             union all select c.id, c.parent_id, m.nm || ' > ' || coalesce(c.name->>'en_US', c.name::text), c.action from ir_ui_menu c join m on c.parent_id = m.id)
             select nm, action from m where action is not null"""
    out = subprocess.run(['psql', DB, '-At', '-F', '|', '-c', sql], capture_output=True, text=True).stdout
    routes = {}
    for line in out.splitlines():
        nm, act = line.split('|')
        routes[re.sub(r'^Export International( > )?', '', nm)] = '/odoo/action-%s' % act.split(',')[1]
    return routes

def applies(e):
    f, w = e['file'], e['what']
    ids = ['EXI-16'] if re.search(r'(home-|party360|match-|reports-|bank|invoice|cash|contract|statement)', f) else []
    if f.endswith('-new.png'): ids.append('EXI-01')
    if f.startswith('phone-home'): ids += ['EXI-02', 'EXI-06']
    if f.startswith('phone-record'): ids += ['EXI-03', 'EXI-09']
    if f.startswith('phone-party360'): ids += ['EXI-02', 'EXI-07']
    if f.startswith('home-'): ids.append('EXI-06')
    if f.startswith('party360'): ids.append('EXI-07')
    if f.startswith('match-'): ids.append('EXI-08')
    if re.search(r'-record(-tab2)?\.png$', f): ids.append('EXI-09')
    if f.startswith('reports-catalog'): ids += ['EXI-05', 'EXI-10']
    elif f.startswith('reports-'): ids.append('EXI-05')
    if re.search(r'(all-639|reports-ar-(list|pivot)|invoice-delivered|bank-payments-to-check|state-list|^approvals)', f) or ('list' in w and f.startswith('menu-')): ids.append('EXI-04')
    if f.startswith('dark-'): ids.append('EXI-13')
    if f == 'login.png': ids.append('EXI-14')
    if re.search(r'(end-of-day|count-the-cash|tax-authority|morning-bank)', f): ids.append('EXI-15')
    if 'connections-to-other-systems' in f: ids.append('EXI-11')
    if f.startswith('ask-'): ids.append('EXI-12')
    return sorted(set(ids))

def main():
    data = json.load(open(os.path.join(G, 'index.json')))['entries']
    routes = menu_routes()
    rows = ['# Screen inventory', '',
            f'{len(data)} screenshots in `docs/ui/gallery/`, each with its route, the role it was captured as, the audit findings that apply (EXI-nn, from the client review of 26 Oct 2026) and the status of each finding. '
            'A finding is "fixed" only when a test that fails without the fix passes with it. Generated by `tests/gen_screen_inventory.py`; statuses live in `tests/inventory_status.json`.', '',
            '## Findings', '', '| ID | Finding | Status |', '|---|---|---|']
    for k, v in FINDINGS.items():
        rows.append(f'| {k} | {v} | {STATUS.get(k, "open")} |')
    rows += ['', '## Screens', '', '| Screenshot | Screen | Route | Role | Findings |', '|---|---|---|---|---|']
    for e in data:
        m = re.match(r'Menu "([^"]+)"', e['what'])
        route = routes.get(m.group(1), '') if m else ''
        if not route and e['file'].startswith(('home-', 'phone-home', 'dark-home')): route = '/odoo'
        if not route and e['file'].startswith(('ask-', 'dark-ask', 'phone-ask')): route = '/odoo/action-ei_assistant.action_ei_assistant'
        if not route and e['file'].startswith(('match-',)): route = '/odoo/action-ei_matching.action_ei_matching'
        if not route and 'party360' in e['file']: route = '/odoo/action-ei_party360.action_ei_party360'
        if not route and e['file'].startswith('reports-'): route = '/odoo/action-ei_reports...'
        if not route and e['file'] == 'login.png': route = '/web/login'
        ids = applies(e)
        rows.append(f"| `{e['file']}` | {e['what'][:110].replace('|', '/')} | `{route}` | {e['user']} | {', '.join(f'{i} ({STATUS.get(i, "open")})' for i in ids) or '-'} |")
    open(os.path.join(ROOT, 'docs', 'ui', 'screen_inventory.md'), 'w').write('\n'.join(rows) + '\n')
    print(len(data), 'screens inventoried')

main()
