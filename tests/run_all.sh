#!/bin/bash
# Fresh database, install every EI module on ODOO 20, run every EI test, write docs/test_results.md from the real log.
# usage: tests/run_all.sh [dbname]     (needs ~/odoo20 - see docs/deployment_runbook.md)
set -u
cd "$(dirname "$0")/.."
. migration/env.sh
DB=${1:-ei_fulltest}
LOG=${TMPDIR:-/tmp}/ei_full_run.log
ei_drop_db "$DB"; createdb "$DB"
ei_odoo -d "$DB" -i "$EI_MODULES" --test-enable --test-tags ei --stop-after-init --without-demo=all --http-port=8179 > "$LOG" 2>&1
ODOO_EXIT=$?
echo "odoo exit code: $ODOO_EXIT"
python3 - "$LOG" <<'PY'
import re, sys, datetime, collections
log = open(sys.argv[1], errors='replace').read()
started = re.findall(r'odoo\.addons\.(\w+)\.tests\.(\w+): Starting (\w+)\.(\w+) \.\.\.', log)
bad = set(re.findall(r'(?:ERROR|FAIL): (\w+)\.(\w+)', log))
summary = re.findall(r'(\d+) failed, (\d+) error\(s\) of (\d+) tests', log)
per = collections.OrderedDict()
for mod, _f, cls, test in started:
    per.setdefault(mod, []).append((cls, test, (cls, test) in bad))
lines = ['# Test results (generated by tests/run_all.sh - real run, not hand-written)\n',
         'Run at %s on **Odoo 20.0** (community nightly 20261018) with a fresh PostgreSQL database; all fourteen EI modules installed.\n' % datetime.datetime.now().strftime('%Y-%m-%d %H:%M'),
         ('**Odoo summary line:** `%s failed, %s error(s) of %s tests`\n' % summary[-1]) if summary else '**No summary line found - treat as FAILED.**\n',
         '| Module | Tests | Passed | Failed |', '|---|---|---|---|']
for mod, ts in per.items():
    lines.append('| %s | %d | %d | %d |' % (mod, len(ts), sum(1 for t in ts if not t[2]), sum(1 for t in ts if t[2])))
lines.append('\n## Every test\n')
for mod, ts in per.items():
    lines.append('\n### %s\n' % mod)
    for cls, test, failed in ts:
        lines.append('- %s `%s.%s`' % ('RED' if failed else 'GREEN', cls, test))
open('docs/test_results.md', 'w').write('\n'.join(lines) + '\n')
print('\n'.join(lines[:18]))
PY

# The real-browser suite is part of the standard run (skip only on purpose: EI_SKIP_E2E=1). It runs on a fresh copy of the
# pristine staging database, so it needs the same machine setup as the unit tests plus Playwright (see tests/e2e/README.md).
E2E_EXIT=0
if [ -z "${EI_SKIP_E2E:-}" ]; then
  tests/run_e2e.sh; E2E_EXIT=$?
  echo "browser suite exit code: $E2E_EXIT  (details: docs/e2e_results.md)"
else
  echo "browser suite SKIPPED on purpose (EI_SKIP_E2E set)"
fi
[ "$ODOO_EXIT" -eq 0 ] && [ "$E2E_EXIT" -eq 0 ]
