#!/usr/bin/env node
// Real-browser end-to-end runner.   node tests/e2e/run.js --base http://127.0.0.1:8372 [--out dir] [--spec name] [--md file]
// Exit code 1 when any check fails. Needs playwright + axe-core (NODE_PATH or a local node_modules).
const fs = require('fs');
const path = require('path');
const { Ctx, launch } = require('./lib');

const arg = (k, d) => { const i = process.argv.indexOf('--' + k); return i > 0 ? process.argv[i + 1] : d; };
const base = arg('base', 'http://127.0.0.1:8372');
const out = arg('out', '/tmp/ei_e2e');
const only = arg('spec', '');
const md = arg('md', '');

(async () => {
  const ctx = new Ctx(base, out);
  const browser = await launch();
  const specs = fs.readdirSync(path.join(__dirname, 'specs')).filter(f => f.endsWith('.js')).sort().filter(f => !only || f.includes(only));
  for (const f of specs) {
    const spec = require(path.join(__dirname, 'specs', f));
    ctx.spec = spec.name; console.log(`\n== ${spec.name}`);
    try { await spec.run(ctx, browser); } catch (e) { ctx.check(false, `spec crashed: ${spec.name}`, String(e.message || e).split('\n')[0].slice(0, 200)); }
  }
  await browser.close();
  const n = k => ctx.rows.filter(r => r.status === k).length;
  console.log(`\n${n('PASS')} passed, ${n('FAIL')} failed, ${n('SKIP')} skipped   (${base})`);
  if (md) {
    const lines = ['# End-to-end browser results (generated by tests/e2e/run.js)', '', `Run at ${new Date().toISOString()} against ${base}. ${n('PASS')} passed, ${n('FAIL')} failed, ${n('SKIP')} skipped.`, '', '| Spec | Status | Check | Detail |', '|---|---|---|---|'];
    for (const r of ctx.rows) lines.push(`| ${r.spec} | ${r.status} | ${r.msg.replace(/\|/g, '/')} | ${(r.detail || '').replace(/\|/g, '/').slice(0, 160)} |`);
    fs.writeFileSync(md, lines.join('\n') + '\n');
  }
  process.exit(ctx.failed ? 1 : 0);
})().catch(e => { console.error(e); process.exit(2); });
